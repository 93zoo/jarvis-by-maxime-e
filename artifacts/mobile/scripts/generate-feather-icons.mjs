// Generates components/featherGlyphs.ts from the feather-icons SVG set.
// Run: node scripts/generate-feather-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const iconsDir = path.join(here, '..', 'node_modules', 'feather-icons', 'dist', 'icons');
const outFile = path.join(here, '..', 'components', 'featherGlyphs.ts');

const out = {};
for (const file of fs.readdirSync(iconsDir).filter((f) => f.endsWith('.svg')).sort()) {
  const name = file.replace(/\.svg$/, '');
  const svg = fs.readFileSync(path.join(iconsDir, file), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '');
  const els = [];
  const re = /<(path|circle|line|polyline|polygon|rect)\b([^/>]*)\/?>(?:<\/\1>)?/g;
  let m;
  while ((m = re.exec(inner))) {
    const attrs = {};
    const are = /([\w-]+)="([^"]*)"/g;
    let a;
    while ((a = are.exec(m[2]))) attrs[a[1]] = a[2];
    els.push({ t: m[1], p: attrs });
  }
  out[name] = els;
}

const ts =
  '// GENERATED by scripts/generate-feather-icons.mjs — do not edit by hand.\n' +
  '// SVG element data for the full Feather icon set (stroke-based, 24x24 viewBox).\n' +
  'export type FeatherGlyphEl = { t: string; p: Record<string, string> };\n' +
  'export const FEATHER_GLYPHS: Record<string, FeatherGlyphEl[]> = ' +
  JSON.stringify(out) +
  ';\n';

fs.writeFileSync(outFile, ts);
console.log('Generated', Object.keys(out).length, 'icons ->', path.relative(process.cwd(), outFile));
